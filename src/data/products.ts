// ---------------------------------------------------------------------------
// Builders
// ---------------------------------------------------------------------------

const weight = (baseQty: number, step = 250, min = 250, max = 5000): SellingUnit => ({
  kind: 'weight',
  baseQty,
  step,
  min,
  max,
})

const count = (label: string, labelPlural: string, approx?: string, max = 10): SellingUnit => ({
  kind: 'count',
  label,
  labelPlural,
  approx,
  step: 1,
  min: 1,
  max,
})

const sizeOptions = (hints: Partial<Record<'small' | 'medium' | 'large', string>> = {}): ProductAttribute => ({
  key: 'size',
  label: 'Size',
  options: (['small', 'medium', 'large'] as const)
    .filter((s) => s in hints)
    .map((s) => ({ value: s, label: s[0].toUpperCase() + s.slice(1), hint: hints[s] })),
})

const attr = (key: AttributeKey, label: string, options: AttributeOption[]): ProductAttribute => ({ key, label, options })

interface VariantSpec {
  attrs: Partial<Record<AttributeKey, string>>
  price: number
  note: string
  inventory?: InventoryStatus
  grade?: Grade
  mrp?: number
  tone?: string
}

function variants(productId: string, specs: VariantSpec[]): ProductVariant[] {
  return specs.map((s) => {
    const suffix = Object.values(s.attrs).join('-') || 'regular'
    return {
      id: `${productId}--${suffix}`,
      sku: `FB-${productId.slice(0, 4).toUpperCase()}-${suffix.toUpperCase().replace(/[^A-Z]/g, '').slice(0, 6)}`,
      productId,
      attributes: s.attrs,
      grade: s.grade ?? 'standard',
      price: s.price,
      mrp: s.mrp,
      inventory: s.inventory ?? 'in_stock',
      note: s.note,
      tone: s.tone,
    }
  })
}

const local = (arrival = 'Received this morning'): Pick<FreshnessInfo, 'arrival' | 'sourcing'> => ({
  arrival,
  sourcing: 'Selected from trusted local suppliers and farm partners around Belagavi.',
})

const regional = (region: string, arrival = 'Received today'): Pick<FreshnessInfo, 'arrival' | 'sourcing'> => ({
  arrival,
  sourcing: `Selected from trusted suppliers bringing produce from ${region}.`,
})

